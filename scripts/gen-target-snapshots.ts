// Regenerates src/adapters/target-snapshots.ts from the saved live fixture.
//   npx tsx scripts/gen-target-snapshots.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';

(globalThis as unknown as { DOMParser: typeof DOMParser }).DOMParser = new JSDOM('').window.DOMParser;
const { parseTargetCms } = await import('../src/adapters/target');

const json = readFileSync('tests/fixtures/target-cms-UIRPDPModalSizeChartsPage.json', 'utf8');
const charts = parseTargetCms(json);
const body =
  `// Generated by scripts/gen-target-snapshots.ts from tests/fixtures/target-cms-UIRPDPModalSizeChartsPage.json.\n` +
  `// Body measurements in cm; ranges are stored as midpoints. Do not edit by hand.\n` +
  `import type { SizeChart } from '../types';\n\n` +
  `export const TARGET_SNAPSHOT_DATE = '2026-10-28';\n\n` +
  `export const TARGET_SNAPSHOTS: Record<string, { name: string; chart: SizeChart }> = ${JSON.stringify(charts, null, 2)};\n`;
writeFileSync('src/adapters/target-snapshots.ts', body);
console.log('wrote snapshots for', Object.keys(charts).join(', '));
